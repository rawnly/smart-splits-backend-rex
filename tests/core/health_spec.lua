local h = require('tests.helpers')

describe('health()', function()
  before_each(function()
    h.reset_backend()
  end)

  after_each(function()
    h.restore()
  end)

  it('reports a reachable server', function()
    local backend = require('smart-splits-backend-rex')
    h.respond('api call server.version', { code = 0, stdout = '{"rex_version":"0.1.0"}' })
    assert.has_no.errors(function()
      backend.health()
    end)
  end)

  it('does not error when the server is unreachable', function()
    local backend = require('smart-splits-backend-rex')
    h.respond('api call', { code = 4 })
    assert.has_no.errors(function()
      backend.health()
    end)
  end)

  it('does not error outside Rex or without the CLI', function()
    local backend = require('smart-splits-backend-rex')
    h.remove_cli()
    assert.has_no.errors(function()
      backend.health()
    end)
    h.reset_backend()
    h.leave_rex()
    assert.has_no.errors(function()
      backend.health()
    end)
  end)
end)
